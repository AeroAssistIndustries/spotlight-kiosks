"""CityPulse ad prices: the one place to change them.

Launch sale: regular prices are shown crossed out with 25% off until the sale ends. After SALE_END the
regular prices apply. The site switches by itself in the browser (assets/pricing.js, written by the build),
and the next build after SALE_END drops the sale wording everywhere.

In page text, write tokens instead of prices; the build fills them in:
  [[P:y1]]  price as HTML: the current price, which switches to the regular price when the sale ends
  [[W:y1]]  the regular price crossed out (hidden once the sale ends)
  [[T:y1]]  the current price as plain text (for page descriptions, form options and attributes)
  [[R:y1]]  the regular price as plain text
  [[SALE]]  short sale note, e.g. "Launch sale: 25% off through March 31, 2027." (empty after the sale)
  [[BADGE]] a small "25% off" badge (empty after the sale)
Keys: y1, y3, y5 (yearly packages), extra (each location after 5, per year), mo (per location per month),
mo3, mo5 (monthly for 3 and 5 locations), per3, per5 (yearly cost per location in the 3 and 5 packages),
save3, save5 (saving vs buying single locations), day (one location per day, yearly plan), mo_yr (monthly x 12), msave5 (yearly vs monthly for 5).
"""
import datetime, json, re

REGULAR = {"y1": 798, "y3": 2198, "y5": 2400, "extra": 600, "mo": 120}
OFF = 25                      # percent off during the launch sale
SALE_END = "2027-03-31"       # last day of the sale (Phoenix time)
SALE_END_TEXT = "March 31, 2027"
# 25% off, rounded down to whole dollars so every price is at least 25% off.
SALE = {k: int(v * (100 - OFF) / 100) for k, v in REGULAR.items()}

def sale_on(today=None):
    today = today or datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=-7))).date()
    return today.isoformat() <= SALE_END

def table(base):
    t = dict(base)
    t["mo3"], t["mo5"] = base["mo"] * 3, base["mo"] * 5
    t["per3"], t["per5"] = base["y3"] / 3, base["y5"] / 5
    t["save3"], t["save5"] = base["y1"] * 3 - base["y3"], base["y1"] * 5 - base["y5"]
    t["day"] = base["y1"] / 365
    t["mo_yr"] = base["mo"] * 12
    t["msave5"] = base["mo"] * 5 * 12 - base["y5"]
    return t

def money(n, cents=False):
    return f"${n:,.2f}" if cents else f"${round(n):,}"

def fmt(t, k):
    return money(t[k], cents=(k == "day"))

def fill(text):
    """Replace price tokens in built HTML or text."""
    on = sale_on()
    return _fill(text, on, table(SALE if on else REGULAR), table(REGULAR))

def _fill(text, on, now, reg):
    def rep(m):
        if m.group(0) == "[[SALE]]":
            return f'<span class="cp-sale">Launch sale: {OFF}% off through {SALE_END_TEXT}.</span>' if on else ""
        if m.group(0) == "[[BADGE]]":
            return f'<em class="cp-sale cp-badge">{OFF}% off</em>' if on else ""
        kind, key = m.group(1), m.group(2)
        if kind == "T": return fmt(now, key)
        if kind == "R": return fmt(reg, key)
        if kind == "W": return f'<s class="cp-was" aria-label="Regular price {fmt(reg, key)}">{fmt(reg, key)}</s>' if on else ""
        return f'<span class="cp-p" data-reg="{fmt(reg, key)}">{fmt(now, key)}</span>' if on else f'<span class="cp-p">{fmt(reg, key)}</span>'
    return re.sub(r"\[\[SALE\]\]|\[\[BADGE\]\]|\[\[([PWTR]):(\w+)\]\]", rep, text)

def js():
    """assets/pricing.js: the same prices for the site's scripts and kiosk screens, and the switch at the end of the sale."""
    return ("/* Generated by build/pricing.py. Edit prices there, not here. */\n"
            "(function () {\n"
            f"  var REG = {json.dumps(REGULAR)}, SALE = {json.dumps(SALE)}, OFF = {OFF};\n"
            f"  var END = Date.parse(\"{SALE_END}T23:59:59-07:00\"), END_TEXT = \"{SALE_END_TEXT}\";\n"
            "  var on = Date.now() <= END, now = on ? SALE : REG;\n"
            "  var money = function (n) { return \"$\" + Math.round(n).toLocaleString(\"en-US\"); };\n"
            "  function annual(n) { n = Math.max(1, Math.floor(n || 1)); var p = arguments[1] || now; return n <= 1 ? p.y1 : n <= 3 ? p.y3 : n <= 5 ? p.y5 : p.y5 + p.extra * (n - 5); }\n"
            "  window.CP_PRICE = { sale: on, off: OFF, end: END_TEXT, now: now, reg: REG, money: money,\n"
            "    annual: function (n) { return annual(n, now); }, regAnnual: function (n) { return annual(n, REG); },\n"
            "    note: on ? \"Launch sale: \" + OFF + \"% off through \" + END_TEXT + \".\" : \"\" };\n"
            "  /* When the sale is over, show regular prices on pages that were built during it. */\n"
            "  if (!on) {\n"
            "    var swap = function () {\n"
            "      [].forEach.call(document.querySelectorAll(\".cp-p[data-reg]\"), function (el) { el.textContent = el.getAttribute(\"data-reg\"); });\n"
            "      [].forEach.call(document.querySelectorAll(\".cp-was, .cp-sale\"), function (el) { el.hidden = true; el.style.display = \"none\"; });\n"
            "    };\n"
            "    if (document.readyState === \"loading\") document.addEventListener(\"DOMContentLoaded\", swap); else swap();\n"
            "  }\n"
            "})();\n")
